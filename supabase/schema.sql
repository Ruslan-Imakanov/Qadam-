-- ---------- Уведомления в Telegram о новых заявках ----------
-- Токен бота и chat_id админ вводит в admin.html → Настройки (таблица private_settings).
-- Пока они пустые, триггер ничего не делает.
create or replace function public.notify_telegram() returns trigger
language plpgsql security definer set search_path = public, extensions as $$
declare
  tok  text;
  chat text;
  msg  text;
begin
  select value into tok  from private_settings where key = 'telegram_bot_token';
  select value into chat from private_settings where key = 'telegram_chat_id';
  if coalesce(tok, '') = '' or coalesce(chat, '') = '' then
    return new;
  end if;
  if tg_table_name = 'leads' then
    msg := 'Новая заявка №' || new.id || ' (' || new.kind || ')' || chr(10)
        || coalesce(new.name, 'без имени') || ', ' || new.phone || chr(10)
        || coalesce(left(new.message, 500), '')
        || case when new.listing_id is not null then chr(10) || 'Объект id ' || new.listing_id else '' end;
  else
    msg := 'Заказ на оценку №' || new.id || ' (' || new.object_category || ')' || chr(10)
        || coalesce(new.name, 'без имени') || ', ' || new.phone || chr(10)
        || coalesce(new.purpose, '') || chr(10)
        || coalesce(left(new.object_description, 500), '');
  end if;
  perform net.http_post(
    url     := 'https://api.telegram.org/bot' || tok || '/sendMessage',
    body    := jsonb_build_object('chat_id', chat, 'text', msg),
    headers := '{"Content-Type": "application/json"}'::jsonb
  );
  return new;
exception when others then
  return new;  -- уведомление не должно мешать сохранению заявки
end $$;

