-- Публичный контент: читают все, пишет админ
do $$
declare t text;
begin
  foreach t in array array['settings','cities','districts','valuation_purposes','checklists','process_steps',
                           'glossary','price_index','valuation_factors']
  loop
    execute format('drop policy if exists %I_read on public.%I', t, t);
    execute format('create policy %I_read on public.%I for select using (true)', t, t);
    execute format('drop policy if exists %I_admin on public.%I', t, t);
    execute format('create policy %I_admin on public.%I for all using (public.is_admin()) with check (public.is_admin())', t, t);
  end loop;
  -- Таблицы с флагом активности: посетитель видит только активное
  foreach t in array array['services','valuation_types','faq','mortgage_programs','agents']
  loop
    execute format('drop policy if exists %I_read on public.%I', t, t);
    execute format('create policy %I_read on public.%I for select using (is_active or public.is_staff())', t, t);
    execute format('drop policy if exists %I_admin on public.%I', t, t);
    execute format('create policy %I_admin on public.%I for all using (public.is_admin()) with check (public.is_admin())', t, t);
  end loop;
end $$;

