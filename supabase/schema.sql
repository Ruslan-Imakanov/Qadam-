-- Агентство недвижимости и оценки — схема БД (Supabase / Postgres)
-- Выполняется один раз в Supabase → SQL Editor (или как миграция).
-- После неё — seed.sql (справочники, услуги, статьи, демо-объекты).
--
-- Доступ (RLS):
--   * посетитель сайта (anon)   — читает опубликованное, отправляет заявки/отзывы;
--   * agent (агент/оценщик)     — работает с объектами, заявками, заказами на оценку;
--   * admin                     — всё, включая контент, настройки и роли.
--   Первый зарегистрированный пользователь автоматически становится admin,
--   все следующие получают роль 'user' (без доступа) — админ повышает их сам.
-- ============================================================

create extension if not exists pg_net with schema extensions;

-- ---------- Профили и роли ----------
create table if not exists public.profiles (
  id          uuid primary key references auth.users on delete cascade,
  email       text,
  full_name   text,
  phone       text,
  role        text not null default 'user' check (role in ('admin','agent','user')),
  created_at  timestamptz not null default now()
);

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists(select 1 from profiles where id = auth.uid() and role = 'admin')
$$;

create or replace function public.is_staff() returns boolean
language sql stable security definer set search_path = public as $$
  select exists(select 1 from profiles where id = auth.uid() and role in ('admin','agent'))
$$;

-- Есть ли уже администратор (для экрана первичной настройки в admin.html)
create or replace function public.has_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists(select 1 from profiles where role = 'admin')
$$;

create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into profiles (id, email, full_name, role)
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data->>'full_name', ''),
    case when exists(select 1 from profiles where role = 'admin') then 'user' else 'admin' end
  )
  on conflict (id) do nothing;
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- Общий триггер updated_at
create or replace function public.touch_updated_at() returns trigger
language plpgsql as $$ begin new.updated_at = now(); return new; end $$;

