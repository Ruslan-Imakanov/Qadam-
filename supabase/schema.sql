-- просматривать вложения могут только сотрудники.
drop policy if exists incoming_insert on storage.objects;
create policy incoming_insert on storage.objects for insert with check (bucket_id = 'incoming');
drop policy if exists incoming_staff_read on storage.objects;
create policy incoming_staff_read on storage.objects for select using (bucket_id = 'incoming' and public.is_staff());
drop policy if exists incoming_staff_delete on storage.objects;
create policy incoming_staff_delete on storage.objects for delete using (bucket_id = 'incoming' and public.is_staff());
